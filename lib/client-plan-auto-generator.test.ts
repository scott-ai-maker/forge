import { describe, it, expect, vi, beforeEach } from 'vitest'
import {
  autoGenerateOrUpdateClientWorkoutPlan,
  isPlanCoachCertified,
  CORE_TRAINING_PROFILE_FIELDS,
} from './client-plan-auto-generator'
import { supabaseAdmin } from './supabase'

vi.mock('./supabase', () => ({
  supabaseAdmin: vi.fn(),
}))

describe('Client Plan Auto-Generator (lib/client-plan-auto-generator)', () => {
  const mockClientId = 'athlete-christine-123'
  const mockCoachId = 'coach-gordon-456'

  let mockFrom: ReturnType<typeof vi.fn>

  beforeEach(() => {
    vi.clearAllMocks()
  })

  describe('isPlanCoachCertified', () => {
    it('returns false for null or undefined plan', () => {
      expect(isPlanCoachCertified(null, null)).toBe(false)
      expect(isPlanCoachCertified(undefined, undefined)).toBe(false)
      expect(isPlanCoachCertified({}, null)).toBe(false)
    })

    it('returns true when plan record has is_certified: true', () => {
      expect(isPlanCoachCertified(null, { is_certified: true })).toBe(true)
    })

    it('returns true when planJson has isCertifiedByCoach: true', () => {
      expect(isPlanCoachCertified({ isCertifiedByCoach: true })).toBe(true)
    })

    it('returns true when planJson has coachCertifiedAt timestamp', () => {
      expect(isPlanCoachCertified({ coachCertifiedAt: '2026-10-27T17:38:00Z' })).toBe(true)
    })

    it('returns true when planJson has safetyGateCertified: true', () => {
      expect(isPlanCoachCertified({ safetyGateCertified: true })).toBe(true)
    })

    it('returns true when planJson was generated by coach', () => {
      expect(isPlanCoachCertified({ generatedBy: 'coach' })).toBe(true)
      expect(isPlanCoachCertified({ generatedByCoachId: mockCoachId })).toBe(true)
      expect(isPlanCoachCertified({ certifiedBy: 'Coach Gordon' })).toBe(true)
    })

    it('returns false for automated system draft plans', () => {
      expect(
        isPlanCoachCertified({
          generatedBy: 'system_auto_sync',
          isCertifiedByCoach: false,
          safetyGateCertified: false,
        })
      ).toBe(false)
    })
  })

  describe('autoGenerateOrUpdateClientWorkoutPlan', () => {
    it('returns skipped when client has no fitness profile', async () => {
      mockFrom = vi.fn((table: string) => ({
        select: vi.fn().mockReturnThis(),
        eq: vi.fn().mockReturnThis(),
        order: vi.fn().mockReturnThis(),
        limit: vi.fn().mockReturnThis(),
        maybeSingle: vi.fn().mockResolvedValue({ data: null, error: null }),
      }))
      vi.mocked(supabaseAdmin).mockReturnValue({ from: mockFrom } as unknown as ReturnType<typeof supabaseAdmin>)

      const result = await autoGenerateOrUpdateClientWorkoutPlan({
        clientId: mockClientId,
        trigger: 'profile_update',
        updatedFields: ['experienceLevel'],
      })

      expect(result.status).toBe('skipped')
      expect(result.message).toContain('No fitness profile found')
    })

    it('preserves coach-certified plan and flags for coach review without overwrite', async () => {
      const mockCoachCertifiedPlan = {
        id: 'plan-bespoke-789',
        name: 'Christine — Bespoke Master Coach Protocol',
        plan_json: {
          isCertifiedByCoach: true,
          coachCertifiedAt: '2026-10-27T17:38:00Z',
          certifiedBy: 'Coach Gordon (NASM Master Trainer)',
          workouts: [{ day: 1, focus: 'Coach Special' }],
        },
      }

      const updatePlanMock = vi.fn().mockReturnThis()
      const insertMessageMock = vi.fn().mockResolvedValue({ error: null })

      mockFrom = vi.fn((table: string) => {
        if (table === 'clients') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: { id: mockClientId, full_name: 'Christine DeGreenia', designated_coach_id: mockCoachId },
              error: null,
            }),
          }
        }
        if (table === 'fitness_profiles') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: {
                user_id: mockClientId,
                age: 41,
                sex: 'female',
                experience_level: 'beginner',
                equipment_access: ['bodyweight'],
                fitness_goal: 'FAT LOSS',
                training_days_per_week: 4,
              },
              error: null,
            }),
          }
        }
        if (table === 'client_intake_forms' || table === 'body_composition_analyses' || table === 'nasm_assessments') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            order: vi.fn().mockReturnThis(),
            limit: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({ data: null, error: null }),
          }
        }
        if (table === 'workout_plans') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            order: vi.fn().mockReturnThis(),
            limit: vi.fn().mockResolvedValue({
              data: [mockCoachCertifiedPlan],
              error: null,
            }),
            update: updatePlanMock.mockReturnValue({
              eq: vi.fn().mockResolvedValue({ error: null }),
            }),
          }
        }
        if (table === 'coach_client_messages') {
          return {
            insert: insertMessageMock,
          }
        }
        return {
          select: vi.fn().mockReturnThis(),
          eq: vi.fn().mockReturnThis(),
        }
      })
      vi.mocked(supabaseAdmin).mockReturnValue({ from: mockFrom } as unknown as ReturnType<typeof supabaseAdmin>)

      const result = await autoGenerateOrUpdateClientWorkoutPlan({
        clientId: mockClientId,
        trigger: 'profile_update',
        updatedFields: ['experienceLevel', 'equipmentAccess'],
      })

      expect(result.status).toBe('preserved_certified')
      expect(result.preservedPlan).toBe(true)
      expect(result.planId).toBe('plan-bespoke-789')
      expect(updatePlanMock).toHaveBeenCalled()
      const updateCallArgs = updatePlanMock.mock.calls[0][0]
      expect(updateCallArgs.plan_json.pendingCoachReview).toBe(true)
      expect(updateCallArgs.plan_json.profileChangeSummary.changedFields).toEqual(['experienceLevel', 'equipmentAccess'])
      expect(insertMessageMock).toHaveBeenCalled()
    })

    it('immediately auto-generates NASM OPT program when client completes onboarding with no prior plan', async () => {
      const insertPlanMock = vi.fn().mockReturnValue({
        select: vi.fn().mockReturnValue({
          single: vi.fn().mockResolvedValue({ data: { id: 'new-plan-auto-111' }, error: null }),
        }),
      })
      const insertMessageMock = vi.fn().mockResolvedValue({ error: null })

      mockFrom = vi.fn((table: string) => {
        if (table === 'clients') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: { id: mockClientId, full_name: 'Christine DeGreenia', designated_coach_id: mockCoachId },
              error: null,
            }),
          }
        }
        if (table === 'fitness_profiles') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: {
                user_id: mockClientId,
                age: 41,
                sex: 'female',
                experience_level: 'beginner',
                equipment_access: ['bodyweight'],
                fitness_goal: 'fat_loss',
                training_days_per_week: 4,
              },
              error: null,
            }),
          }
        }
        if (table === 'workout_plans') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            order: vi.fn().mockReturnThis(),
            limit: vi.fn().mockResolvedValue({ data: [], error: null }),
            insert: insertPlanMock,
          }
        }
        if (table === 'exercise_library_entries') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            in: vi.fn().mockReturnThis(),
            limit: vi.fn().mockResolvedValue({
              data: [
                {
                  id: 'ex-1',
                  name: 'Incline Push Up',
                  media_image_url: 'https://cdn.example.com/incline-pushup.jpg',
                  media_video_url: 'https://youtube.com/watch?v=demo1',
                },
                {
                  id: 'ex-2',
                  name: 'Box Squat',
                  media_image_url: 'https://cdn.example.com/box-squat.jpg',
                  media_video_url: 'https://youtube.com/watch?v=demo2',
                },
              ],
              error: null,
            }),
          }
        }
        if (table === 'equipment_library_entries') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            in: vi.fn().mockResolvedValue({ data: [], error: null }),
          }
        }
        if (table === 'coach_client_messages') {
          return {
            insert: insertMessageMock,
          }
        }
        return {
          select: vi.fn().mockReturnThis(),
          eq: vi.fn().mockReturnThis(),
          order: vi.fn().mockReturnThis(),
          limit: vi.fn().mockReturnThis(),
          maybeSingle: vi.fn().mockResolvedValue({ data: null, error: null }),
        }
      })
      vi.mocked(supabaseAdmin).mockReturnValue({ from: mockFrom } as unknown as ReturnType<typeof supabaseAdmin>)

      const result = await autoGenerateOrUpdateClientWorkoutPlan({
        clientId: mockClientId,
        trigger: 'onboarding',
      })

      expect(result.status).toBe('generated')
      expect(result.planId).toBe('new-plan-auto-111')
      expect(result.nasmOptPhase).toBe(1)
      expect(result.sessionsPerWeek).toBe(4)
      expect(insertPlanMock).toHaveBeenCalled()
      const insertedRow = insertPlanMock.mock.calls[0][0]
      expect(insertedRow.nasm_opt_phase).toBe(1)
      expect(insertedRow.plan_json.generatedBy).toBe('system_auto_sync')
      expect(insertedRow.plan_json.autoGenerateTrigger).toBe('onboarding')
      expect(insertedRow.plan_json.isCertifiedByCoach).toBe(false)
      expect(insertMessageMock).toHaveBeenCalled()
    })

    it('immediately regenerates uncertified plan when client updates core profile parameters', async () => {
      const mockUncertifiedExistingPlan = {
        id: 'plan-uncertified-draft-999',
        name: 'Christine — Old AI Plan',
        plan_json: {
          generatedBy: 'system_auto_sync',
          isCertifiedByCoach: false,
          safetyGateCertified: false,
        },
      }

      const updatePlanMock = vi.fn().mockReturnValue({
        eq: vi.fn().mockReturnValue({
          select: vi.fn().mockReturnValue({
            single: vi.fn().mockResolvedValue({ data: { id: 'plan-uncertified-draft-999' }, error: null }),
          }),
        }),
      })

      mockFrom = vi.fn((table: string) => {
        if (table === 'clients') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: { id: mockClientId, full_name: 'Christine DeGreenia', designated_coach_id: mockCoachId },
              error: null,
            }),
          }
        }
        if (table === 'fitness_profiles') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            maybeSingle: vi.fn().mockResolvedValue({
              data: {
                user_id: mockClientId,
                age: 41,
                sex: 'female',
                experience_level: 'beginner',
                equipment_access: ['bodyweight'],
                fitness_goal: 'fat_loss',
                training_days_per_week: 4,
              },
              error: null,
            }),
          }
        }
        if (table === 'workout_plans') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            order: vi.fn().mockReturnThis(),
            limit: vi.fn().mockResolvedValue({ data: [mockUncertifiedExistingPlan], error: null }),
            update: updatePlanMock,
          }
        }
        if (table === 'exercise_library_entries') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            in: vi.fn().mockReturnThis(),
            limit: vi.fn().mockResolvedValue({ data: [], error: null }),
          }
        }
        if (table === 'equipment_library_entries') {
          return {
            select: vi.fn().mockReturnThis(),
            eq: vi.fn().mockReturnThis(),
            in: vi.fn().mockResolvedValue({ data: [], error: null }),
          }
        }
        if (table === 'coach_client_messages') {
          return {
            insert: vi.fn().mockResolvedValue({ error: null }),
          }
        }
        return {
          select: vi.fn().mockReturnThis(),
          eq: vi.fn().mockReturnThis(),
          order: vi.fn().mockReturnThis(),
          limit: vi.fn().mockReturnThis(),
          maybeSingle: vi.fn().mockResolvedValue({ data: null, error: null }),
        }
      })
      vi.mocked(supabaseAdmin).mockReturnValue({ from: mockFrom } as unknown as ReturnType<typeof supabaseAdmin>)

      const result = await autoGenerateOrUpdateClientWorkoutPlan({
        clientId: mockClientId,
        trigger: 'profile_update',
        updatedFields: ['experienceLevel'],
      })

      expect(result.status).toBe('generated')
      expect(result.planId).toBe('plan-uncertified-draft-999')
      expect(result.preservedPlan).toBe(false)
      expect(updatePlanMock).toHaveBeenCalled()
      const updatedRow = updatePlanMock.mock.calls[0][0]
      expect(updatedRow.plan_json.autoGenerateTrigger).toBe('profile_update')
      expect(updatedRow.plan_json.updatedCoreFields).toEqual(['experienceLevel'])
    })
  })
})
