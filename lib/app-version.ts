/**
 * Helper to parse a Semantic Version string into { major, minor, patch }
 */
export function parseSemVer(version: string): { major: number; minor: number; patch: number } {
  const clean = version.replace(/^v/, '')
  const parts = clean.split('.').map(p => parseInt(p, 10))
  return {
    major: parts[0] || 0,
    minor: parts[1] || 0,
    patch: parts[2] || 0,
  }
}

/**
 * Returns true if versionA is strictly greater than versionB
 */
export function isNewerVersion(versionA: string, versionB: string): boolean {
  const a = parseSemVer(versionA)
  const b = parseSemVer(versionB)
  if (a.major !== b.major) return a.major > b.major
  if (a.minor !== b.minor) return a.minor > b.minor
  return a.patch > b.patch
}
